NAMES = {" ": "space", "!": "excl", "'": "apos", ".": "dot", ",": "comma", ":": "colon",
         "-": "dash", "%": "pct", "°": "deg", "/": "slash"}


def resname(ch):
    if ch.isalpha():
        return f"px_{ch.lower()}"
    if ch.isdigit():
        return f"px_{ch}"
    return f"px_{NAMES[ch]}"


def draw(ch, rows):
    w, h = 6 * S, 7 * S            # 5 cells + 1 cell of right-side spacing
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    for j, row in enumerate(rows):
        for i, bit in enumerate(row):
            if bit == "1":
                d.rectangle([i * S, j * S, (i + 1) * S - 1, (j + 1) * S - 1], fill=(255, 255, 255, 255))
    img.save(OUT / f"{resname(ch)}.png")
    return w, h


def xml_escape(ch):
    return {"'": "&apos;", "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;"}.get(ch, ch)


